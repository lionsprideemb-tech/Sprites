#!/usr/bin/env python3
"""Read-only coordinate mapping for manual Orpheus 64px sprite corrections.

Never changes or approves art; prints candidate pixels and shows native geometry
on a grid. Source is generated by the existing successful DS64 workflow.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import struct,hashlib,base64,json,collections
P=Path("report/ds64_readability")
OUT=Path("report/ds64_microfix")
OUT.mkdir(parents=True,exist_ok=True)
FILES=["vibrava_back","flygon_front"]
FONT=ImageFont.load_default()
def getidx(buf):
 vals=[0]*4096;k=0
 for y0 in range(0,64,8):
  for x0 in range(0,64,8):
   for dy in range(8):
    for dx in range(0,8,2):
     b=buf[k];k+=1
     vals[(y0+dy)*64+x0+dx]=b&15
     vals[(y0+dy)*64+x0+dx+1]=b>>4
 return vals
def show(img,x,y,scale):
 out=img.resize((img.width*scale,img.height*scale),Image.Resampling.NEAREST)
 return out
def crop_axes(img,region,scale=10):
 x0,y0,x1,y1=region
 cropped=img.crop(region)
 board=Image.new("RGB",((x1-x0)*scale+88,(y1-y0)*scale+92),"#edf2f5")
 bdraw=ImageDraw.Draw(board)
 board.paste(show(cropped,0,0,scale).convert("RGB"),(52,44))
 for x in range(x0,x1):
  xx=52+(x-x0)*scale
  if x%4==0:
   bdraw.line((xx,42,xx,44+(y1-y0)*scale),fill="#B9C2CC",width=1)
   bdraw.text((xx,20),str(x),fill="#25313b",font=FONT)
 for y in range(y0,y1):
  yy=44+(y-y0)*scale
  if y%4==0:
   bdraw.line((50,yy,52+(x1-x0)*scale,yy),fill="#B9C2CC",width=1)
   bdraw.text((4,yy),str(y),fill="#25313b",font=FONT)
 return board
H=1050;W=1350
sheet=Image.new("RGB",(W,H),"#F7F8F7")
d=ImageDraw.Draw(sheet)
d.text((20,20),"ORPHEUS / 64px PIXEL-COORDINATE DIAGNOSTIC — UNAPPROVED",fill="#25313b")
d.text((20,40),"Actual current 64px pixels and indexed palette; 8x sprite + labeled 10x local subregion grid",fill="#536171")
summary=[]
for line,name in enumerate(FILES):
 img=Image.open(P/f"{name}_contrast64.png").convert("RGBA")
 idx=getidx((P/f"{name}_4bpp_tiles.bin").read_bytes())
 words=struct.unpack("<16H",(P/f"{name}_bgr555_palette.bin").read_bytes())
 bg=Image.new("RGBA",(64,64),(236,241,246,255));bg.alpha_composite(img)
 y=75+line*485
 sheet.paste(show(bg,0,0,7).convert("RGB"),(18,y+25))
 region=(23,4,60,42) if name=="vibrava_back" else (9,5,47,43)
 crop=bg.crop(region)
 detail=crop_axes(crop,(0,0,crop.width,crop.height),9)
 # crop_axes labels offset relative to ROI; include absolute ROI label explicitly
 sheet.paste(detail,(520,y+25))
 d.text((18,y),name.replace("_"," ").title()+" • source 64px, nearest 7x",fill="#25313b")
 d.text((525,y),f"Detail original x:{region[0]}–{region[2]-1} y:{region[1]}–{region[3]-1} (9x)",fill="#25313b")
 # Candidate 1-pixel interior color spikes where surrounding opaque cardinal
 # neighbors majority >2 and source pixel is not the deep outline shade.
 candidates=[]
 for yy in range(1,63):
  for xx in range(1,63):
   k=yy*64+xx
   c=idx[k]
   if c<=1:continue
   near=[idx[k-1],idx[k+1],idx[k-64],idx[k+64]]
   active=[v for v in near if v]
   if len(active)!=4:continue
   color,count=collections.Counter(active).most_common(1)[0]
   if color!=c and count>=3 and color>1:
    candidates.append({"x":xx,"y":yy,"was":c,"suggested":color,"support":count})
 # Show top plausible hits only, do not apply
 candidates=sorted(candidates,key=lambda p:(-p["support"],p["y"],p["x"]))
 print("MICRO_DIAGNOSTIC",json.dumps({"name":name,"roi":region,"candidates":candidates[:40],"candidateCount":len(candidates),"colors":list(set(idx))},sort_keys=True))
 summary.append({"name":name,"region":region,"candidates":candidates})
sheet_path=OUT/"pixel_grid_diagnostic.png"
sheet.save(sheet_path,optimize=True)
(OUT/"candidate_coordinates.json").write_text(json.dumps(summary,indent=2))
print("MICRO_DIAGNOSTIC_IMAGE_START")
print(base64.b64encode(sheet_path.read_bytes()).decode("ascii"))
print("MICRO_DIAGNOSTIC_IMAGE_END")
